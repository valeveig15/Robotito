"use strict";
const assert=require("node:assert/strict");
const c=require("../collaboration-domain.js");
const user=id=>({id,source:"trusted-server-auth"});
assert.throws(()=>c.actorId({id:"alice"}),/Authentication/);
assert.throws(()=>c.makeGrant({recipient:"bob",permission:"read",scope:{type:"subject",id:"s",subject:"Física"}}),/Authentication/);
const scope={type:"topic",id:"t1",subject:"Biología",topic:"Célula"};
const record={owner:"alice",type:"academic-material",subject:"Biología",topic:"Célula",sessionId:"cl1",
 name:"Notas.md",text:"Sólo material docente",faceEmbedding:[1,2,3],
 voicePrint:"secret",personalMemory:"private"};
const grant=c.makeGrant({actor:user("alice"),recipient:"bob",permission:"read",scope});
assert.equal(c.access(grant,user("bob"),"read",record),true);
assert.equal(c.access(grant,user("bob"),"write",record),false);
assert.equal(c.access(grant,user("eve"),"read",record),false);
assert.equal(c.access(grant,user("bob"),"read",{...record,topic:"Otra"}),false);
assert.equal(c.access(grant,user("bob"),"read",{...record,subject:"Física"}),false);
assert.throws(()=>c.academicOnly({owner:"alice",type:"face",subject:"Biología",topic:"Célula"},scope,"alice"));
assert.equal(c.access(grant,user("bob"),"read",{...record,owner:"eve"}),false,
 "Matching subject must never leak a different owner\u0027s material");
const shared=c.academicOnly(record,scope,"alice");
assert.equal(shared.type,"academic-material");
assert.equal(shared.text,"Sólo material docente");
assert.equal("faceEmbedding" in shared,false);
assert.equal("voicePrint" in shared,false);
assert.equal("personalMemory" in shared,false);
assert.throws(()=>c.revokeGrant(grant,user("eve"),1),/Forbidden/);
assert.throws(()=>c.revokeGrant(grant,user("alice"),2),/Revision/);
const revoked=c.revokeGrant(grant,user("alice"),1);
assert.equal(c.access(revoked,user("bob"),"read",record),false);
assert.throws(()=>c.makeGrant({actor:user("alice"),recipient:"alice",permission:"write",scope}));
let group=c.makeGroup({actor:user("alice"),title:"Estudio de biología",subject:"Biología"});
assert.throws(()=>c.memberChange(group,user("bob"),"bob","editor",1),/Not a group member/);
group=c.memberChange(group,user("alice"),"bob","editor",1);
assert.equal(group.members.bob.role,"editor");
assert.throws(()=>c.memberChange(group,user("bob"),"eve","editor",group.revision),/Forbidden/);
assert.throws(()=>c.postMessage(group,user("eve"),"hola",group.revision),/Not a group member/);
assert.throws(()=>c.postMessage(group,user("bob"),"Hola",1),/Revision conflict/);
group=c.postMessage(group,user("bob"),"Hola equipo",group.revision);
assert.equal(group.messages.at(-1).author,"bob");
group=c.memberChange(group,user("alice"),"eve","reader",group.revision);
assert.throws(()=>c.postMessage(group,user("eve"),"Quiero escribir",group.revision),/Read-only/);
assert.throws(()=>c.deadlineChange(group,user("bob"),"2026-02-30",group.revision),/Invalid deadline/);
assert.throws(()=>c.deadlineChange(group,user("eve"),"2026-12-12",group.revision),/Forbidden/);
group=c.deadlineChange(group,user("alice"),"2026-11-22",group.revision);
assert.equal(group.deadline,"2026-11-22");
const now=Date.parse("2026-11-15T10:00:00Z");
assert.deepEqual(c.reminderPlan(group,user("bob"),now),[],"Notifications default to opt-out");
group=c.notificationChoice(group,user("bob"),true,"UTC",group.revision);
let reminders=c.reminderPlan(group,user("bob"),now);
assert.equal(reminders.length,1,"Opted-in member gets an eligible morning reminder");
assert.equal(reminders[0].daysRemaining,7);
const key=reminders[0].dedupeKey;
assert.equal(c.reminderPlan(group,user("bob"),now)[0].dedupeKey,key,"Stable idempotency key");
assert.deepEqual(c.reminderPlan(group,user("bob"),Date.parse("2026-11-15T02:00:00Z")),[]);
assert.deepEqual(c.reminderPlan(group,user("bob"),Date.parse("2026-11-01T10:00:00Z")),[]);
group=c.deadlineChange(group,user("alice"),"2026-11-21",group.revision);
assert.notEqual(c.reminderPlan(group,user("bob"),now)[0]?.dedupeKey,key,"Deadline revision changes identity");
group=c.memberChange(group,user("alice"),"bob","remove",group.revision);
assert.throws(()=>c.reminderPlan(group,user("bob"),now),/Not a group member/);
console.log("P16/P17 academic ACL, revocation, group roles and reminder planning: passed");
