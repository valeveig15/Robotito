"use strict";
const assert=require("node:assert/strict");
const path=require("node:path");
const fs=require("node:fs");
const {evaluate,ensureManifest,wilson}=require("../scripts/evaluate-p08-identity.js");
const fixture=JSON.parse(fs.readFileSync(path.join(__dirname,"fixtures",
 "p08-synthetic-evaluation.json"),"utf8"));
let checks=0;
function eq(actual,expected,label){assert.deepEqual(actual,expected,label);checks++;}
const r=evaluate(fixture);
eq(r.synthetic,true,"Synthetic manifest cannot be presented as a real test");
eq(r.validatedOnHardware,false,"Aggregate metrics cannot invent physical validation");
eq(r.calibrationTrials,2,"Calibration is counted separately");
eq(r.testTrials,4,"Only held-out test attempts enter metric denominators");
eq(r.summary.falseAcceptance.n,2,"Two impostor attempts");
eq(r.summary.falseAcceptance.numerator,1,"One synthetic false acceptance");
eq(r.summary.falseAcceptance.rate,.5,"Synthetic FAR = 1/2");
eq(r.summary.falseRejection.n,2,"Two genuine attempts");
eq(r.summary.falseRejection.numerator,1,"One synthetic false rejection");
eq(r.summary.falseRejection.rate,.5,"Synthetic FRR = 1/2");
eq(r.summary.abstentions.numerator,1,"Explicit abstention counted");
eq(r.summary.latencyMs.median,300,"Nearest-rank synthetic median");
eq(r.summary.latencyMs.p95,500,"Nearest-rank synthetic p95");
eq(r.summary.insufficientSample,true,"Small synthetic sample is inadequate for claims");
eq(r.groups.device.iphone.trials,1,"Device stratification works");
eq(r.groups.scenario.replay.falseAcceptance.rate,0,"Impostor replay rejection counted");
eq(wilson(0,0).rate,null,"Zero denominator is not falsely reported as 0%");
const bad=JSON.parse(JSON.stringify(fixture));
bad.trials[0].consent=false;
assert.throws(()=>ensureManifest(bad),/consent/i);checks++;
bad.trials[0].consent=true;
bad.trials[0].voicePrint=[1,2,3];
assert.throws(()=>ensureManifest(bad),/metadata only/i);checks++;
delete bad.trials[0].voicePrint;
bad.trials[1].id=bad.trials[0].id;
assert.throws(()=>ensureManifest(bad),/duplicate/i);checks++;
bad.trials[1].id="cal2";
bad.trials=bad.trials.filter(t=>t.split==="calibration");
assert.throws(()=>ensureManifest(bad),/separate/i);checks++;
const leaked={...fixture,faces:[{embedding:[.1,.2]}]};
assert.throws(()=>ensureManifest(leaked),/Invalid P08 local evaluation manifest/i);checks++;
assert.equal(JSON.stringify(r).includes("p01"),false);checks++;
assert.equal(JSON.stringify(r).includes("p02"),false);checks++;
console.log("P08 private metadata evaluator:",checks,"checks; no biometric export or false physical validation");
