"use strict";
const assert=require("node:assert/strict");
const P=require("../learning-games-policy.js");
const material="Membrana celular: Barrera selectiva\nATP: Trifosfato de adenosina\nDifusión: Movimiento neto a favor de gradiente\nATP: Duplicado";
const items=P.parseSource(material);
assert.equal(items.length,3);
assert.equal(items[1].answer,"Trifosfato de adenosina");
assert.equal(P.parseSource("no question\nfoo")[0],undefined);
assert.equal(P.parseSource("a: b").length,0);
assert.equal(P.parseSource("Afirmación :: Respuesta").length,1);
const options=P.choices(items,items[0],1);
assert.equal(options.length,3);
assert.equal(options.filter(x=>x.id===items[0].id).length,1);
assert.notEqual(options[0].id,items[0].id);
assert.throws(()=>P.choices(items,{id:"wrong"},1),/Target/);
assert.equal(P.nextDifficulty([]),"intro");
assert.equal(P.nextDifficulty([{},{}]),"intro");
assert.equal(P.nextDifficulty([{correct:true},{correct:true},{correct:false}]),"practica");
assert.equal(P.nextDifficulty(Array(5).fill({correct:true})),"desafio");
assert.equal(P.nextDifficulty(Array(5).fill({correct:false})),"intro");
assert.equal(P.nextItem(items,[]).id,items[0].id);
assert.equal(P.nextItem(items,[{id:items[0].id,correct:true}]).id,items[1].id);
assert.equal(P.nextItem(items,[{id:items[1].id,correct:false}]).id,items[1].id);
assert.equal(P.grade("Trifosfato de adenosina","trifosfato DE adenosina."),true);
assert.equal(P.grade("ATP","ADP"),false);
const member=P.sanitizeMember({name:" Ana ",minutes:45,completed:3});
assert.deepEqual(member,{name:"Ana",minutes:45,completed:3});
assert.throws(()=>P.sanitizeMember({name:"",minutes:45,completed:2}),/name/);
assert.throws(()=>P.sanitizeMember({name:"Ana",minutes:-1,completed:2}),/minutes/);
assert.throws(()=>P.sanitizeMember({name:"Ana",minutes:20.4,completed:2}),/minutes/);
assert.equal(P.groupStats([member,{name:"Luz",minutes:30,completed:1}]).minutes,75);
assert.equal(P.groupStats([member,{name:"Luz",minutes:30,completed:1}]).completed,4);
assert.equal(P.groupStats([]).maxMinutes,1);
assert.equal(P.season("cumpleanos"),"cumpleanos");
assert.equal(P.season("<script>"),"normal");
assert.ok(P.parseSource(Array(150).fill("Tema: Respuesta").map((x,i)=>i+": "+x).join("\n")).length<=P.MAX_ITEMS);
console.log("P79-P82 grounded quizzes, adaptive mistakes, group totals, bounded source and themes: passed");
