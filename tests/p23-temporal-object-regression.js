"use strict";
const assert=require("node:assert/strict");
const {createTracker,createFingerCounter}=require("../object-tracker.js");
let now=1000;
const tracker=createTracker({now:()=>now,ttlMs:1900,minFrames:3});
assert.equal(tracker.current(),null);
assert.equal(tracker.observe([{class:"cup",score:.89}],now),null);
now+=150;assert.equal(tracker.observe([{class:"bowl",score:.90}],now),null);
now+=150;assert.equal(tracker.observe([{class:"cup",score:.87}],now),null);
now+=150;assert.equal(tracker.observe([{class:"bowl",score:.91}],now),null,
 "Conflicting cup/bowl predictions cannot be identified as either object");
tracker.reset();
now+=150;tracker.observe([{class:"cat",score:.89},{class:"dog",score:.31}],now);
now+=150;tracker.observe([{class:"cat",score:.85},{class:"dog",score:.33}],now);
now+=150;const good=tracker.observe([{class:"cat",score:.87}],now);
assert.equal(good.label,"cat");assert.equal(good.votes,3);
now+=2200;assert.equal(tracker.current(now),null,"Results expire after the camera frame ages");
tracker.reset();
now+=50;tracker.observe([{class:"cup",score:.64},{class:"bowl",score:.62}],now);
now+=50;tracker.observe([{class:"cup",score:.65},{class:"bowl",score:.63}],now);
now+=50;assert.equal(tracker.observe([{class:"cup",score:.66},{class:"bowl",score:.64}],now),null,
 "Closely competing labels require a more confident observation");
tracker.reset();
now+=100;tracker.observe([{class:"person",score:.95},{class:"book",score:.84}],now);
now+=100;tracker.observe([{class:"person",score:.95},{class:"book",score:.84}],now);
now+=100;const nonPerson=tracker.observe([{class:"person",score:.95},{class:"book",score:.84}],now);
assert.equal(nonPerson.label,"book","Person detections should not hide a clear object");
const fingers=createFingerCounter({now:()=>now,minFrames:3});
assert.equal(fingers.observe(2,now),null);
assert.equal(fingers.observe(3,now+100),null);
assert.equal(fingers.observe(2,now+200),null);
assert.equal(fingers.observe(2,now+300),null);
assert.equal(fingers.observe(2,now+400),2);
assert.equal(fingers.observe(5,now+500),null,"One inconsistent hand frame cannot change a count");
assert.equal(fingers.observe(99,now+600),null,"Impossible count clears observations");
assert.equal(fingers.observe(5,now+700),null);
fingers.observe(5,now+800);
assert.equal(fingers.observe(5,now+900),5);
assert.equal(fingers.observe(null,now+1000),null);
console.log("P23 temporal object consensus, close-label uncertainty, expiry and stable finger counts: passed");
