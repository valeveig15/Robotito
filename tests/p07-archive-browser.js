"use strict";
const assert=require("node:assert/strict");
const {runBrowserTest}=require("./browser-test-harness.js");
runBrowserTest("p07-archive",async test=>{
 const {page,context,baseURL}=test;let count=0;
 const eq=(a,b,m)=>{assert.deepEqual(a,b,m);count++;};
 await page.goto(baseURL,{waitUntil:"domcontentloaded"});await page.waitForFunction(()=>ROBOTITO_MEMORY?.active&&ROBOTITO_ARCHIVE);
 const other=await context.newPage();await other.goto(baseURL,{waitUntil:"domcontentloaded"});await other.waitForFunction(()=>ROBOTITO_MEMORY?.active);
 test.phase("large-binary-archive-and-encryption");
 const result=await page.evaluate(async()=>{
  const s=ROBOTITO_STORE,a=ROBOTITO_ARCHIVE;let checks=0;
  const check=(x,m)=>{if(!x)throw Error(m);checks++;};
  const rejects=async(fn,m)=>{let failed=false;try{await fn();}catch{failed=true;}check(failed,m);};
  const bytes=new Uint8Array(17*1024*1024+3);for(let i=0;i<bytes.length;i++)bytes[i]=(i*31+17)%256;
  await s.putRecordWithBlob({id:"large-file",owner:"Ada",type:"pdfs",blobId:"large-data",data:{title:"Large fixture"}},new Blob([bytes],{type:"application/pdf"}),{type:"pdf"});
  await s.putRecord({id:"original",owner:"Ada",type:"memories",data:{text:"Original before restore"}});
  localStorage.setItem("robotito.p07-test-setting","before");
  const plain=await a.exportFile();window.__p07Archive=plain;
  check(plain.size>17*1024*1024,"Large file is included in archive");
  check(plain.size<18*1024*1024,"Binary format avoids base64 expansion");
  await rejects(()=>s.exportBackup(),"Legacy JSON safely refuses oversized file");
  const parsed=await a.readFile(plain);
  check(parsed.summary.blobs===1,"Large file metadata round trip");
  check(parsed.snapshot.blobs[0].blobBytes.byteLength===bytes.length,"All binary bytes retained");
  const restored=new Uint8Array(parsed.snapshot.blobs[0].blobBytes);
  check(restored.every((v,i)=>v===bytes[i]),"Every large-file byte is exact");
  const password="Archive P07 testing passphrase!";
  const encrypted=await a.exportFile({password}),decrypted=await a.readFile(encrypted,{password});
  check(decrypted.summary.binaryBytes===bytes.length,"Encrypted large archive round trip");
  await rejects(()=>a.readFile(encrypted,{password:"different password for tests"}),"Wrong passphrase cannot restore");
  const damaged=new Uint8Array(await encrypted.arrayBuffer());damaged[damaged.length-1]^=1;
  await rejects(()=>a.readFile(new Blob([damaged]),{password}),"Authenticated ciphertext detects tampering");
  const raw=new Uint8Array(await plain.arrayBuffer());raw[raw.length-1]^=1;
  await rejects(()=>a.readFile(new Blob([raw])),"File checksum detects damaged bytes");
  raw[raw.length-1]^=1;raw[44]^=1;
  await rejects(()=>a.readFile(new Blob([raw])),"Metadata checksum detects damage");
  await rejects(()=>a.readFile(plain.slice(0,plain.size-3)),"Truncated archive rejected");
  await rejects(()=>a.readFile(new Blob([plain,"trailing bytes"])),"Trailing bytes rejected");
  const metadataLength=new DataView(await plain.slice(8,12).arrayBuffer()).getUint32(0);
  const metadata=JSON.parse(await plain.slice(44,44+metadataLength).text());
  const copy=()=>structuredClone(metadata);
  const version=copy();version.dbVersion=999;await rejects(()=>a.validate(version),"Future schema rejected");
  const duplicate=copy();duplicate.records.push(duplicate.records[0]);await rejects(()=>a.validate(duplicate),"Duplicate IDs rejected");
  const wrongOwner=copy();wrongOwner.records.find(r=>r.id==="large-file").owner="Bob";await rejects(()=>a.validate(wrongOwner),"Cross-owner blob rejected");
  const oversized=copy();oversized.blobs[0].size=a.limits.file+1;await rejects(()=>a.validate(oversized),"Per-file limit enforced");
  const pref=copy();pref.preferences.push({key:"unrelated-account",value:"x"});await rejects(()=>a.validate(pref),"Unrelated localStorage keys rejected");
  const count=(await s.queryRecords({owner:"Ada",limit:Infinity})).length;
  await rejects(()=>a.restoreFile(plain,{confirmation:"yes"}),"Exact confirmation required");
  check((await s.queryRecords({owner:"Ada",limit:Infinity})).length===count,"Rejected imports leave live data unchanged");
  // Force a synchronous storage error after staging a checkpoint/clear.
  await s.discardRestoreUndo();
  const put=IDBObjectStore.prototype.put;let injected=false;
  IDBObjectStore.prototype.put=function(value,...rest){
   if(!injected&&this.name==="records"){injected=true;throw new DOMException("Injected quota exhaustion","QuotaExceededError");}
   return put.call(this,value,...rest);
  };
  try{await rejects(()=>s.replaceSnapshot(parsed.snapshot,{confirmation:"RESTAURAR"}),"Quota failure aborts atomic replacement");}
  finally{IDBObjectStore.prototype.put=put;}
  check(injected,"Quota failure reached actual IndexedDB write path");
  check((await s.getRecord("original")).data.text==="Original before restore","Aborted restore preserves records");
  check((await s.getBlob("large-data")).size===bytes.length,"Aborted restore preserves large binary");
  check(await s.getRestoreUndoInfo()===null,"Aborted restore does not leave a misleading checkpoint");
  await s.putRecord({id:"after-export",owner:"Ada",type:"memories",data:{text:"Restore must remove this"}});
  localStorage.setItem("robotito.p07-test-setting","after");
  await a.restoreFile(plain,{confirmation:"RESTAURAR"});
  await s.applyPendingPreferences();
  check(!await s.getRecord("after-export"),"Restore replaces the full snapshot");
  check(localStorage.getItem("robotito.p07-test-setting")==="before","Device preferences restored");
  check(Boolean(await s.getRestoreUndoInfo()),"Undo checkpoint is available");
  const exported=await a.readFile(await a.exportFile());
  check(!exported.snapshot.state.some(r=>r.key==="robotito.restore.undo.v1"),"Internal checkpoint never leaves in backup");
  return {checks,bytes:bytes.length,size:plain.size};
 });count+=result.checks;
 test.phase("stale-tab-after-restore");
 eq(await other.evaluate(async()=>{try{await ROBOTITO_STORE.putRecord({id:"stale-resurrection",owner:"Ada",type:"memories",data:{text:"Stale tab"}});return false;}catch{return true;}}),true,"Old tab cannot resurrect pre-restore state");
 eq(await page.evaluate(async()=>await ROBOTITO_STORE.getRecord("stale-resurrection")),null,"Stale write left no record");
 await other.close();
 test.phase("undo-after-reload");
 await page.reload();await page.waitForFunction(()=>ROBOTITO_MEMORY?.active);
 eq(await page.evaluate(async()=>Boolean(await ROBOTITO_STORE.getRestoreUndoInfo())),true,"Checkpoint survives reload");
 await page.evaluate(async()=>{await ROBOTITO_STORE.undoLastRestore({confirmation:"DESHACER"});await ROBOTITO_STORE.applyPendingPreferences();});
 const undo=await page.evaluate(async()=>({record:!!await ROBOTITO_STORE.getRecord("after-export"),setting:localStorage.getItem("robotito.p07-test-setting"),checkpoint:await ROBOTITO_STORE.getRestoreUndoInfo()}));
 eq(undo,{record:true,setting:"after",checkpoint:null},"One-step undo restores previous data and settings");
 test.phase("large-file-download-ui");
 await page.addStyleTag({content:"#languageGate{display:none!important}"});await page.locator('[data-tab="memory"]').click();await page.locator("details.memory-backup summary").click();
 eq(await page.locator("#memoryBackupFormat").inputValue(),"complete","Complete archive is the default");
 const [download]=await Promise.all([page.waitForEvent("download"),page.locator("#downloadMemoryBackup").click()]);
 assert.match(download.suggestedFilename(),/^robotito-memory-.*\.robotito$/);count++;
 eq(Boolean(await download.path()),true,"Large complete archive is downloadable");
 test.report.result={checks:count,largeFileBytes:result.bytes,archiveBytes:result.size,quotaInjection:true,physicalHardware:false};
 console.log("P07 "+test.engineName+" large archives, authenticated encryption, restore/undo and stale tabs:",count,"checks;",result.bytes,"binary bytes");
}).catch(e=>{console.error(e);process.exitCode=1;});
