"use strict";
const assert=require("node:assert/strict");
const P=require("../class-markers-policy.js");
assert.deepEqual(P.colors,["yellow","green","blue","pink"]);
assert.equal(P.sanitize("  Hola\n mundo  "), "Hola mundo");
assert.equal(P.clock(0),"00:00:00");
assert.equal(P.clock(61000),"00:01:01");
assert.equal(P.clock(3661000),"01:01:01");
const item=P.marker({id:"marker-1",sessionId:"class-A",offsetMs:175000,color:"green",note:"Fórmula esencial"});
assert.equal(item.color,"green");assert.equal(item.offsetMs,175000);assert.equal(item.sessionId,"class-A");
assert.equal(P.marker({id:"marker-2",sessionId:"A",offsetMs:1,color:"not-known"}).color,"yellow");
assert.throws(()=>P.marker({sessionId:"",offsetMs:1000}),/Cannot bookmark/);
assert.throws(()=>P.marker({sessionId:"A",offsetMs:-1}),RangeError);
assert.throws(()=>P.marker({sessionId:"A",offsetMs:86401000}),RangeError);
assert.throws(()=>P.marker({sessionId:"A",offsetMs:NaN}),RangeError);
const transcript=[{offsetMs:0,text:"Introducción"},{offsetMs:5000,text:"Primera fórmula"},{offsetMs:15000,text:"Conclusión"}];
assert.equal(P.align(transcript,6200).text,"Primera fórmula");
assert.equal(P.align(transcript,16000).text,"Conclusión");
assert.equal(P.align(transcript,-1000),null);
assert.equal(P.align([],100),null);
console.log("P76–P78: color and timing validation, strict metadata, seek alignment passed");
