"use strict";
const assert=require("node:assert/strict");
require("../p33-p35-policy.js");
const p=globalThis.ROBOTITO_P33_P35;
assert.equal(p.batteryThreshold(60,50,false),50);
assert.equal(p.batteryThreshold(51,19,false),20);
assert.equal(p.batteryThreshold(20,5,false),5);
assert.equal(p.batteryThreshold(3,3,false),null);
assert.equal(p.batteryThreshold(5,8,false),null);
assert.equal(p.batteryThreshold(60,10,true),null);
assert.equal(p.batteryThreshold(null,4,false),5);
assert.equal(p.batteryThreshold(null,90,false),null);
assert.equal(p.batteryThreshold(20,NaN,false),null);
assert.equal(p.batteryThreshold(20,-1,false),null);
const day=new Date(2026,10,17,6,0);
assert.equal(p.birthdaySlot(new Date(2026,10,17,5,59)),"night");
assert.equal(p.birthdaySlot(day),"morning");
assert.equal(p.birthdaySlot(new Date(2026,10,17,12,0)),"afternoon");
assert.equal(p.birthdaySlot(new Date(2026,10,17,18,0)),"night");
assert.equal(p.birthdayDay(day),"2026-11-17");
assert.equal(p.isBirthday("2000-11-17",day),true);
assert.equal(p.isBirthday("2000-12-17",day),false);
assert.equal(p.isBirthday("invalid",day),false);
const person={id:"opaque-id",name:"Ada"};
assert.equal(p.birthdayKey(person,day),p.birthdayKey({...person,name:"Changed"},day));
assert.notEqual(p.birthdayKey(person,day),p.birthdayKey(person,new Date(2026,10,17,12)));
assert.notEqual(p.birthdayKey(person,day),p.birthdayKey({id:"other"},day));
assert.equal(p.birthdayKey({},day),null);
assert.equal(p.normalizedTitle("El Árbol: Vol. II!"),"el arbol vol ii");
assert.equal(p.bookIdentity({title:"La Casa",authors:["A"]}),p.bookIdentity({title:"La casa",authors:["A"]}));
assert.notEqual(p.bookIdentity({title:"La Casa",authors:["A"]}),p.bookIdentity({title:"La Casa",authors:["B"]}));
assert.equal(p.bookIdentity({title:"La Casa",industryIdentifiers:[{type:"ISBN_13",identifier:"9780123456789"}]}),"isbn:9780123456789");
assert.equal(p.safeHttps("javascript:alert(1)"),"");
assert.equal(p.safeHttps("http://evil.example/x"),"");
assert.equal(p.safeHttps("http://books.google.com/x"),"https://books.google.com/x");
assert.equal(p.safeHttps("https://books.google.com/x"),"https://books.google.com/x");
console.log("P33-P35 policy: thresholds, birthday slots, personal keys, metadata provenance and URLs passed");
