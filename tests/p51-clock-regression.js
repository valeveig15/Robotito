"use strict";
const assert=require("node:assert/strict");
const P=require("../clock-countdown-policy.js");
assert.match(P.readableTime("2026-11-18T10:11:12"),/10:11:12/);
assert.throws(()=>P.readableTime("bad-time"),/Invalid/);
const start=new Date(2026,10,18,10,0,0),same=P.nextLocalTime(start,10,0);
assert.ok(same>start.getTime());assert.equal(new Date(same).getDate(),19);
const future=P.nextLocalTime(start,12,30);
assert.equal(new Date(future).getHours(),12);
assert.equal(new Date(future).getMinutes(),30);
assert.throws(()=>P.nextLocalTime(start,24,0),RangeError);
assert.throws(()=>P.nextLocalTime(start,4,60),RangeError);
assert.deepEqual(P.remaining(0,90061000),{days:1,hours:1,minutes:1,seconds:1,totalSeconds:90061});
assert.equal(P.remaining(1000,500).totalSeconds,0);
assert.match(P.speakTimeText(start,"es"),/Son las/);
assert.match(P.speakTimeText(start,"en"),/It is/);
assert.match(P.speakTimeText(start,"pt"),/São/);
assert.match(P.speakTimeText(start,"fr"),/Il est/);
assert.match(P.speakTimeText(start,"it"),/Sono le/);
assert.match(P.speakTimeText(start,"de"),/Es ist/);
console.log("P51 clock formatting, next local date, countdown and six-language phrasing passed");
