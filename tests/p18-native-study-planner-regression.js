"use strict";
const assert=require("node:assert/strict");
const {createPlanner}=require("../study-planner.js");
const map=new Map(),storage={getItem:k=>map.get(k)||null,setItem:(k,v)=>map.set(k,v)};
let today=new Date("2026-11-16T12:00:00");
const planner=createPlanner({storage,now:()=>today});
planner.addSubject("Biología",5);
const late=planner.addTask({title:"Preparar parcial",subject:"Biología",due:"2026-11-15",priority:1,minutes:120});
const regular=planner.addTask({title:"Leer 10 páginas",subject:"Literatura",priority:5,minutes:20});
let plan=planner.todayPlan();
assert.equal(plan.tasks[0].id,late.id,"Past-deadline task supersedes normal priority");
assert.equal(plan.tasks[0].stage,"ATRASADA — Superprioridad");
assert.equal(plan.tasks[1].stage,"sin fecha");
today=new Date("2026-12-01T12:00:00");
plan=planner.todayPlan();
assert.equal(plan.tasks[0].stage,"ATRASADA — Superprioridad","Overdue must remain overdue a month later, not repeat weekly");
const tomorrow=planner.addTask({title:"Entrega proyecto",subject:"Física",due:"2026-12-02",minutes:45});
assert.equal(planner.todayPlan().tasks[1].id,tomorrow.id);
assert.equal(planner.todayPlan().tasks[1].stage,"Mañana — Muy urgente");
planner.updateTask(tomorrow.id,{due:"2026-12-05",priority:5});
assert.equal(planner.todayPlan().tasks.find(t=>t.id===tomorrow.id).stage,"Próxima entrega");
planner.addBlock({weekday:2,start:"17:00",end:"18:00"});
assert.equal(planner.todayPlan().availableMinutes,60);
assert.equal(planner.todayPlan().tasks.reduce((x,t)=>x+t.allocated,0),60,"Never schedule more minutes than available");
assert.throws(()=>planner.addBlock({weekday:2,start:"17:30",end:"18:30"}),/superpone/);
assert.throws(()=>planner.addTask({title:"Invalida",due:"2026-02-30"}),/imposible/);
assert.throws(()=>planner.addTask({title:"Invalida",priority:6}),/inválidos/);
assert.throws(()=>planner.updateTask(late.id,{due:"2026-13-01"}),/imposible/);
assert.equal(createPlanner({storage}).snapshot().tasks.length,3,"Storage survives page reload");
planner.updateTask(late.id,{done:true});
assert.equal(planner.todayPlan().tasks.some(t=>t.id===late.id),false);
assert.equal(createPlanner({storage}).snapshot().tasks.find(t=>t.id===late.id).done,true);
planner.updateTask(tomorrow.id,{done:true});
assert.equal(planner.todayPlan().allDone,false);
assert.equal(planner.speech("Terminé tarea Leer 10 páginas").handled,true);
assert.equal(planner.todayPlan().allDone,true);
planner.updateTask(regular.id,{done:false});
assert.equal(planner.todayPlan().allDone,false);
assert.equal(planner.speech("Anotá tarea estudiar velocidad para Física").handled,true);
assert.equal(planner.todayPlan().tasks.some(t=>t.title==="estudiar velocidad"),true);
assert.equal(planner.speech("Tengo tres tareas").handled,false);
planner.removeTask(regular.id);
assert.equal(planner.snapshot().tasks.some(t=>t.id===regular.id),false);
assert.ok(planner.snapshot().subjects.some(s=>s.name==="Física"));
const broken={getItem:()=>null,setItem:()=>{throw new Error("QuotaExceeded");}};
const failing=createPlanner({storage:broken});
assert.throws(()=>failing.addTask({title:"No persistir"}),/QuotaExceeded/);
assert.equal(failing.snapshot().tasks.length,0,"Failed write must not pretend that task was saved");
console.log("P18 native study planner deadlines, manual priorities, persistence and voice: passed");
