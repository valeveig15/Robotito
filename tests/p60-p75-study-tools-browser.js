"use strict";
const assert=require("node:assert/strict");
const {runBrowserTest}=require("./browser-test-harness.js");
runBrowserTest("p60-p75-study-tools",async test=>{
 const {page,baseURL}=test;
 await page.goto(baseURL,{waitUntil:"domcontentloaded"});
 await page.waitForFunction(()=>document.documentElement.dataset.robotitoUiReady==="true");
 if(await page.locator("#languageGate").isVisible()){
  await page.locator('[data-start-language="es"]').click();
  await page.locator('#avatarChoices [data-avatar-id="panda"]').click();
 }
 await page.locator('[data-tab="tasks"]').click();
 test.phase("timer-and-stopwatch-visible");
 assert.equal(await page.locator("#studyTimerDisplay").innerText(),"00:00:00");
 await page.locator("#studyTimerMode").selectOption("countdown");
 await page.locator("#studyTimerMinutes").fill("2");
 await page.locator("#studyTimerStart").click();
 await page.waitForTimeout(400);
 assert.match(await page.locator("#studyTimerDisplay").innerText(),/^00:01:/);
 await page.locator("#studyTimerPause").click();
 await page.locator("#studyTimerReset").click();
 assert.equal(await page.locator("#studyTimerDisplay").innerText(),"00:00:00");
 test.phase("session-recording-and-real-weekly-metrics");
 await page.locator("#studySessionSubject").fill("Química");
 await page.locator("#studyMinutesDone").fill("35");
 await page.locator("#studyRecordSession").click();
 await page.waitForFunction(()=>document.getElementById("studyDeskStatus").textContent.includes("registrada"));
 await page.locator("#studyDesk details").nth(2).locator("summary").click();
 assert.match(await page.locator("#studyWeekSummary").innerText(),/35 minutos esta semana/);
 await page.locator("#studyDesk details").nth(2).locator("summary").click();
 test.phase("flashcards-review-and-spacing");
 await page.locator("#studyDesk details").nth(3).locator("summary").click();
 await page.locator("#flashcardFront").fill("¿Qué es el ATP?");
 await page.locator("#flashcardBack").fill("Adenosín trifosfato");
 await page.locator("#studyFlashcardForm button[type=submit]").click();
 await page.waitForFunction(()=>document.querySelector(".study-card-front")?.textContent.includes("ATP"));
 await page.locator(".study-flashcards button").first().click();
 assert.match(await page.locator(".study-card-back").innerText(),/Adenosín trifosfato/);
 await page.locator(".study-card-actions button").first().click();
 await page.waitForFunction(()=>document.querySelector(".study-flashcards").textContent.includes("Sin tarjetas pendientes"));
 test.phase("focus-mode-and-readable-content-are-user-controlled");
 await page.locator("#studyDesk details").nth(4).locator("summary").click();
 await page.locator("#studyFocusMode").check();
 assert.equal(await page.locator("body").evaluate(e=>e.classList.contains("robotito-focus-mode")),true);
 await page.locator("#studyReadingText").fill("Membrana celular\nFosfolípidos y proteínas\nTransporte activo");
 await page.locator("#studyBionic").check();
 assert.ok(await page.locator("#studyReadingPreview strong").count()>0);
 assert.match(await page.locator("#studyReadingPreview").innerText(),/Membrana celular/);
 assert.match(await page.locator("#studyMindMap").innerText(),/Fosfolípidos y proteínas/);
 await page.locator("#studyReadingTheme").selectOption("dark");
 assert.equal(await page.locator("#studyReadingPreview").getAttribute("data-theme"),"dark");
 test.phase("agenda-session-scheduled-locally");
 await page.locator("#studyDesk details").nth(4).locator("summary").click();
 await page.locator("#studyDesk details").nth(1).locator("summary").click();
 const upcoming=await page.evaluate(()=>{
  const date=new Date(Date.now()+2*3600000);
  const local=new Date(date.getTime()-date.getTimezoneOffset()*60000).toISOString().slice(0,16);
  return local;
 });
 await page.locator("#studyAgendaSubject").fill("Biología");
 await page.locator("#studyAgendaDate").fill(upcoming);
 await page.locator("#studyAgendaForm button[type=submit]").click();
 await page.waitForFunction(()=>document.querySelectorAll(".study-agenda-row").length===1);
 assert.match(await page.locator(".study-agenda-row").innerText(),/Biología/);
 assert.deepEqual(test.report.pageErrors,[]);
});
